<?php

declare(strict_types=1);

namespace App\State\Processor\Notification;

use ApiPlatform\Metadata\Operation;
use ApiPlatform\State\ProcessorInterface;
use App\Service\Notification\NotificationChannelManager;

/** @implements ProcessorInterface<object, void> */
final readonly class DeleteNotificationChannelProcessor implements ProcessorInterface
{
    public function __construct(private NotificationChannelManager $manager)
    {
    }

    public function process(mixed $data, Operation $operation, array $uriVariables = [], array $context = []): void
    {
        $id = $uriVariables['id'] ?? '';
        $this->manager->delete(\is_string($id) ? $id : '');
    }
}
